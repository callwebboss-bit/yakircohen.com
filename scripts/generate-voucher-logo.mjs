/**
 * מייצר את lib/sales/voucher-logo.generated.ts: הלוגו (public/images/logo.svg)
 * כ-data URL, לציור אישור ההזמנה ושובר המתנה בעמדת המכירות.
 *
 * למה: בדיקת הלוגו 7.10.2026 מצאה שהקנבס טוען את הלוגו מהרשת, ושכשל בטעינה
 * נבלע בשקט ונשמר לכל חיי העמוד. הבעלים יכול היה לשתף שובר בלי לוגו ולא
 * לדעת. עם הקובץ בתוך החבילה אין בקשת רשת, ולכן אין מה שייכשל בדרך.
 *
 * הקובץ נכנס כמו שהוא, בלי החיתוך של logoSvg, כדי שהציור לא ישתנה: הקנבס
 * מחשב את היחס מהמידות הטבעיות (400pt על 200pt, כלומר 533 על 267 פיקסלים),
 * ואותן מידות יוצאות גם מה-data URL (נמדד ב-Chromium, 7.10.2026).
 *
 * Run: node scripts/generate-voucher-logo.mjs          כתיבה
 *      node scripts/generate-voucher-logo.mjs --check  נכשל אם הקובץ לא מעודכן
 *
 * lib/sales/voucher-logo.test.ts בודק את אותו דבר בכל npm test.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LOGO_PATH } from "./lib/brand-logo.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_PATH = path.join(root, "lib", "sales", "voucher-logo.generated.ts");
const REL_OUT = path.relative(root, OUT_PATH);

export function buildVoucherLogoModule() {
  const svg = fs.readFileSync(LOGO_PATH);
  /* base64 ולא encodeURIComponent: נתוני הנתיב מלאים ברווחים, וכל רווח היה
     הופך ל-3 תווים */
  const dataUrl = `data:image/svg+xml;base64,${svg.toString("base64")}`;
  return [
    "/** AUTO-GENERATED by scripts/generate-voucher-logo.mjs - do not edit */",
    "",
    "/**",
    " * public/images/logo.svg כמו שהוא, כ-data URL. הקנבס של עמדת המכירות מצייר",
    " * ממנו בלי בקשת רשת (בדיקת הלוגו 7.10.2026). אחרי שינוי בלוגו מריצים שוב",
    " * את הסקריפט, ו-lib/sales/voucher-logo.test.ts נכשל עד שמריצים.",
    " */",
    `export const VOUCHER_LOGO_DATA_URL = ${JSON.stringify(dataUrl)};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const body = buildVoucherLogoModule();
  const current = fs.existsSync(OUT_PATH) ? fs.readFileSync(OUT_PATH, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== body) {
      console.error(`${REL_OUT} לא תואם ל-public/images/logo.svg. להריץ: node scripts/generate-voucher-logo.mjs`);
      process.exit(1);
    }
    console.log(`${REL_OUT} מעודכן`);
  } else if (current === body) {
    console.log(`${REL_OUT} כבר מעודכן`);
  } else {
    fs.writeFileSync(OUT_PATH, body);
    console.log(`נכתב ${REL_OUT} (${body.length} תווים)`);
  }
}
