export const GLOSSARY_TERM_MAP: Readonly<Record<string, GlossaryTerm>> =
  Object.freeze(
    Object.fromEntries(GLOSSARY_TERMS.map((term) => [term.slug, term])),
  );

export const GLOSSARY_PHRASE_TO_SLUG: Readonly<Record<string, string>> =
  Object.freeze(
    Object.fromEntries(
      GLOSSARY_TERMS.flatMap((term) => [
        [term.termHe, term.slug],
        ...(term.termEn ? [[term.termEn, term.slug]] : []),
        ...((term.aliases ?? []).map((alias) => [alias, term.slug] as const)),
      ]),
    ),
  );

export const GLOSSARY_TOOLTIP_PHRASES = Object.freeze(
  Object.entries(GLOSSARY_PHRASE_TO_SLUG)
    .map(([phrase, slug]) => ({ phrase, slug }))
    .sort((a, b) => b.phrase.length - a.phrase.length),
);

export function getAllGlossarySlugs(): string[] {
  return GLOSSARY_TERMS.map((term) => term.slug);
}

export function getGlossaryTermBySlug(slug: string): GlossaryTerm | undefined {
  return GLOSSARY_TERM_MAP[slug];
}

export function getGlossaryCategory(
  id: GlossaryCategoryId,
): (typeof GLOSSARY_CATEGORIES)[number] | undefined {
  return GLOSSARY_CATEGORIES.find((category) => category.id === id);
}

export function getGlossaryTermsByCategory(
  id: GlossaryCategoryId,
): GlossaryTerm[] {
  return GLOSSARY_TERMS.filter((term) => term.category === id);
}

