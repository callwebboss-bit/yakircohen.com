/* כמה יוצא לכל אחד: אותו חישוב כמו טופס השיר (calcSongOffer), כדי שהסכום כאן
   והסכום בטופס יהיו זהים. הבעלים, 11.10.2026: "כולם מקליטים שיר משותף". */
const GROUP_SIZES = [4, 6, 8, 10, 12] as const;
const nis = (amount: number) => `${amount.toLocaleString("he-IL")} ₪`;
function perPersonLine(size: number): string {
  const total = calcSongOffer([], size).totalWithVat;
  return `${nis(total)} כולל מע״מ לכל הקבוצה, בערך ${nis(Math.round(total / size))} לאדם`;
}

